const WARDROBE_SHARED = ['clothes wardrobe', 'clothing wardrobe', 'freestanding wardrobe', 'wardrobe cabinet']

/** Older library labels that are the same article as the catalogue name. */
const NAME_ALIASES = {
  'sofa 2 seater': '2-seater sofa',
  'sofa 3 seater': '3-seater sofa',
  'l shaped sofas': 'L shape sofa',
  box: 'Medium box — kitchen and general',
}

/** Lowercase, ignore apostrophes, and treat spaces, hyphens and slashes as the same gap. */
export function canonicalItemKey(value) {
  return String(value ?? '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

const SYNONYMS_BY_KEY = new Map(
  Object.entries(INVENTORY_ITEM_SYNONYMS).map(([name, synonyms]) => [canonicalItemKey(name), synonyms]),
)

for (const name of ['Single wardrobe', 'Double wardrobe', 'Triple wardrobe', 'Four-door wardrobe', 'Sliding-door wardrobe']) {
  const key = canonicalItemKey(name)
  SYNONYMS_BY_KEY.set(key, [...(SYNONYMS_BY_KEY.get(key) || []), ...WARDROBE_SHARED])
}

/** @param {string} name */
export function canonicalItemName(name) {
  return NAME_ALIASES[canonicalItemKey(name)] || String(name ?? '')
}

/** @param {string} name */
export function synonymsForItemName(name) {
  return SYNONYMS_BY_KEY.get(canonicalItemKey(canonicalItemName(name))) || []
}
