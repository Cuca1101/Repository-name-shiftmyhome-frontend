/** Category key for “Other items” (catalogue + custom-item form on Step 2). */
export const OTHER_ITEMS_CATEGORY_KEY = 'other'

export function getFlattenedCatalogEntries() {
  const out = []
  for (const key of CATEGORY_ORDER) {
    const cat = INVENTORY_BY_CATEGORY[key]
    if (!cat) continue

    for (const item of cat.items) {
      out.push({
        categoryKey: key,
        categoryLabel: cat.label,
        item,
      })
    }
  }
  return out
}

export function getCatalogItem(itemId) {
  for (const key of CATEGORY_ORDER) {
    const cat = INVENTORY_BY_CATEGORY[key]
    if (!cat) continue

    const found = cat.items.find((item) => item.id === itemId)
    if (found) {
      return {
        categoryKey: key,
        categoryLabel: cat.label,
        item: found,
      }
    }
  }

  return null
}
